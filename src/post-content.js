export function passage(text, code) {
  text = clean(text); const output = []; let cursor = 0; let who = PEOPLE[code] || '플레이어';
  const re = new RegExp(`(?:${actor}\\s*)?“([^”]+)”`, 'g');
  const narrate = raw => {
    const t = raw.trim().replace(/^(?:라고|이라|라|고)\s*(?:말한다|말함|답한다|답함|한다|받는다|잇는다|덧붙인다)?[.,。]?\s*/, '').trim();
    if (t && !/^(?:[.,。/]|→)/.test(t) && !/처음이면|없으면|있으면|얕은 교류|교류가 얕|원래 |SNAP-|주 완료|주 행동|→|조건은|대체한다/.test(t)) output.push(stage(t));
  };
  for (const m of text.matchAll(re)) {
    const before = text.slice(cursor, m.index);
    const subjects = [...before.matchAll(new RegExp(`${actor}(?:가|이|는|은|도)`, 'g'))];
    if (subjects.length) who = subjects.at(-1)[1];
    narrate(before);
    if (m[1]) who = m[1] === '교사' ? '화학 교사' : m[1];
    output.push(say(who, m[2])); cursor = m.index + m[0].length;
  }
  narrate(text.slice(cursor)); return output;
}
