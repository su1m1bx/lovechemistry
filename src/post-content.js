export function postContent(s, c, event) {
  if (event === 'R') return rContent(s, c);
  if (event === 'B') return bContent(s, c);
  if (event === 'T') return tContent(s, c);
  if (event === 'X') {
    if (c === 'HE') return { intro: text(c, '헬륨 “정리 순서는 바꾸는 게 낫겠어. 라벨을 먼저 보면 겹치는 걸 줄일 수 있어.” 플레이어 “제 순서도 보셨어요?” 헬륨 “봤어. 그래서 앞의 두 개를 옮겼고.” 손가락이 종이 위에서 멎는다. 헬륨 “……해 달라고 한 건 아니었지.”'), choices: rows('LATE-HE-TURN').map((r, i) => ({ label: r[0].replace(/^“|”$/g, ''), lines: [...text(c, r[1]), d(c, '네 종이는 돌려줄게')], main: i < 2 })) };
    return lateContent(s, c, event);
  }
  return uContent(s, c, event);
}

