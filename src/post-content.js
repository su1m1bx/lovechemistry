export function postCommon(id) {
  const day = Number(id.match(/\d+/)[0]); const phase = id.split('-')[1];
  const body = sections[id]?.body; if (!body) throw new Error(`확정 공통 대본이 없습니다: ${id}`);
  const q = body.split('\n').filter(line => /^- (?:서술:|수소|탄소|플레이어|화학 교사)/.test(line)).flatMap(line => {
    const t = line.slice(2); return t.startsWith('서술:') ? [stage(t.slice(3).trim())] : passage(t);
  });
  // Reuse existing data; these scene IDs never become new acquired note IDs.
  const cast = phase === 'NOTE' ? [] : phase === 'AM' ? COMMON_CAST[day] : [...new Set(q.flatMap(line => Object.entries(PEOPLE).filter(([, name]) => line.who === name).map(([c]) => c)))];
  return { q, cast };
}

